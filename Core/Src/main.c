/* 必须在 LTDC / TouchGFX 使用 0xC0000000 之前调用。 */
static void BSP_SDRAM_Init(void)
{
  uint32_t sdclk = HAL_RCC_GetHCLKFreq() / 2U;
  uint32_t cycles = (uint32_t)(((uint64_t)sdclk * 64U) / 4096000U);

  if (SDRAM_SendCmd(FMC_SDRAM_CMD_CLK_ENABLE, 1, 0) != HAL_OK)
  {
    Error_Handler();
  }
  HAL_Delay(1);
  if (SDRAM_SendCmd(FMC_SDRAM_CMD_PALL, 1, 0) != HAL_OK)
  {
    Error_Handler();
  }
  if (SDRAM_SendCmd(FMC_SDRAM_CMD_AUTOREFRESH_MODE, 8, 0) != HAL_OK)
  {
    Error_Handler();
  }
  if (SDRAM_SendCmd(FMC_SDRAM_CMD_LOAD_MODE, 1, 0x0230) != HAL_OK)
  {
    Error_Handler();
  }
  if (cycles <= 20U)
  {
    Error_Handler();
  }
  if (HAL_SDRAM_ProgramRefreshRate(&hsdram1, cycles - 20U) != HAL_OK)
  {
    Error_Handler();
  }
  FMC_Bank1->BTCR[0] = 0x000030D2;
}
